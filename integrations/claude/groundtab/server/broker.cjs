  async runJob(job, onProgress, signal) {
    if (signal?.aborted) throw abortError();
    if (!this.socket || this.socket.readyState !== import_websocket.default.OPEN) {
      throw new Error("GroundTab is not connected. Open the extension in Chrome or Brave and check its connection status.");
    }
    const id = (0, import_node_crypto.randomUUID)();
    const timeoutMs = job.timeoutMs + 5e3;
    const deadlineAt = Date.now() + timeoutMs;
    const result = new Promise((resolve, reject) => {
      const onAbort = () => {
        const pending = this.pending.get(id);
        if (!pending || pending.cancelled) return;
        pending.cancelled = true;
        pending.onProgress = void 0;
        pending.removeAbortListener();
        reject(abortError());
        if (!pending.running) {
          clearTimeout(pending.timer);
          this.pending.delete(id);
          this.pumpJobs();
        }
      };
      const removeAbortListener = () => signal?.removeEventListener("abort", onAbort);
      const timer = setTimeout(() => {
        const pending = this.pending.get(id);
        if (pending?.running) this.runningJobs -= 1;
        pending?.removeAbortListener();
        this.pending.delete(id);
        if (!pending?.cancelled) reject(new Error(`Browser job timed out after ${timeoutMs}ms`));
        this.pumpJobs();
      }, timeoutMs);
      this.pending.set(id, {
        id,
        job,
        deadlineAt,
        running: false,
        onProgress,
        resolve,
        reject,
        timer,
        cancelled: false,
        removeAbortListener
      });
      signal?.addEventListener("abort", onAbort, { once: true });
    });
    onProgress?.({ type: "job_progress", id, phase: "queued", domain: jobDomain(job), elapsedMs: 0 });
    this.pumpJobs();
    return result;
  }
